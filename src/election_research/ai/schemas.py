"""Pydantic data models and schemas for the AI assistant subsystem."""

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class ToolCall(BaseModel):
    """Structured representation of an analytical tool invocation requested by the model."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(description="Unique call identifier")
    name: str = Field(description="Name of the requested tool in the registry")
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Parsed arguments for the tool"
    )


class ChatMessage(BaseModel):
    """Unified message structure for conversational turns and tool responses."""

    model_config = ConfigDict(extra="ignore")

    role: Literal["system", "user", "assistant", "tool"] = Field(description="Message role")
    content: str = Field(default="", description="Textual message payload")
    tool_calls: list[ToolCall] | None = Field(
        default=None, description="Tool calls if generated by assistant"
    )
    tool_call_id: str | None = Field(default=None, description="Reference ID when role is 'tool'")
    name: str | None = Field(default=None, description="Tool name when role is 'tool'")

    def to_dict(self) -> dict[str, Any]:
        """Convert message to dictionary compatible with Hugging Face / OpenAI chat templates."""
        d: dict[str, Any] = {"role": self.role, "content": self.content}
        if self.tool_calls:
            d["tool_calls"] = [
                {
                    "id": tc.id,
                    "type": "function",
                    "function": {"name": tc.name, "arguments": tc.arguments},
                }
                for tc in self.tool_calls
            ]
        if self.tool_call_id:
            d["tool_call_id"] = self.tool_call_id
        if self.name:
            d["name"] = self.name
        return d


class ToolDefinition(BaseModel):
    """Specification of an analytical tool exposed to Qwen3.5-4B."""

    model_config = ConfigDict(extra="ignore")

    name: str
    description: str
    parameters: dict[str, Any]

    def to_hf_tool(self) -> dict[str, Any]:
        """Convert to Hugging Face / JSON schema format for chat completions."""
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.parameters,
            },
        }


class ToolResult(BaseModel):
    """Structured result returned by the ToolExecutor."""

    model_config = ConfigDict(extra="ignore")

    tool_name: str
    arguments: dict[str, Any]
    success: bool
    data: Any = None
    error: str | None = None
    provenance: dict[str, Any] = Field(default_factory=dict)
    record_count: int = 0
    duration_seconds: float = 0.0

    def to_summary_dict(self) -> dict[str, Any]:
        """Compact representation for feeding back into the model context."""
        return {
            "tool": self.tool_name,
            "success": self.success,
            "data": self.data,
            "error": self.error,
            "provenance": self.provenance,
        }


class ModelResponse(BaseModel):
    """Normalized response returned by any AIProvider."""

    model_config = ConfigDict(extra="ignore")

    content: str
    tool_calls: list[ToolCall] = Field(default_factory=list)
    raw_content: str | None = None
    thinking_content: str | None = None
    token_usage: dict[str, int] | None = None
    duration_seconds: float = 0.0


class ProviderHealth(BaseModel):
    """Health check outcome for an AIProvider."""

    model_config = ConfigDict(extra="ignore")

    provider_id: str
    model_id: str
    is_available: bool
    status_message: str
    latency_ms: float = 0.0
    supports_tools: bool = False
